  expect(intent.y).toBeLessThan(architecture.y)
  await page.getByRole('button', { name: /Guardarraíles\. / }).hover()
  await expect(page.locator('.journey-insight')).toContainText('Guías y controles')
  await page.getByRole('button', { name: /Entrega\. / }).hover()
  await expect(page.locator('.journey-insight')).toContainText('Desplegamos el software en desarrollo, preproducción y producción')
  await page.mouse.click(100, 620)
  await expect(page.locator('[data-scene]')).toHaveAttribute('data-scene', 'cover')
  await page.goto('/software-engineering-2_0/#scene=03-repo')
  await page.getByRole('button', { name: /Instrucciones\. / }).hover()
  await expect(page.locator('.node-popover')).toContainText('AGENTS.md y reglas locales')
  await expect(page.locator('.node-popover')).not.toContainText('Instrucciones')
  await expect(page.locator('.diagram-hint')).toHaveCount(0)
  await page.goto('/software-engineering-2_0/#scene=04-guardarrailes')
  await expect(page.locator('.guardrail-definition')).toContainText('procesos repetibles')
  await expect(page.locator('.comparison-next')).toHaveCount(0)
  await page.mouse.click(1100, 540)
  await expect(page.locator('[data-scene]')).toHaveAttribute('data-stage', '1')
  await expect(page.getByRole('heading', { name: 'Blandos · Guían' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Duros · Bloquean' })).toBeVisible()
  await page.goto('/software-engineering-2_0/#scene=05-estructura')
  await page.getByRole('button', { name: /tests\/\. / }).hover()
  await expect(page.locator('.repo-inspector')).toContainText('Pruebas ejecutables')
  await page.getByRole('button', { name: /docs\/design\/\. / }).click()
  await expect(page.locator('.repo-inspector')).toContainText('Experiencia de uso')
  await expect(page).toHaveURL(/#scene=05-estructura$/)
  await page.goto('/software-engineering-2_0/#scene=06-sdd')
  await page.getByRole('button', { name: 'Planificar' }).hover()
  await expect(page.locator('.sdd-message')).toContainText('Elige una solución')
