  await expect(page.locator('.journey-spoke')).toHaveCount(7)
  const map = await page.locator('.journey-map').boundingBox()
  const core = await page.locator('.journey-core').boundingBox()
  expect(Math.abs(core.x + core.width / 2 - map.x - map.width / 2)).toBeLessThan(2)
  expect(Math.abs(core.y + core.height / 2 - map.y - map.height / 2)).toBeLessThan(2)
  expect(await page.locator('.journey-node').allTextContents()).toEqual(['◆Intención', '◆Arquitectura', '◆Guardarraíles', '◆Código', '◆Evidencia', '◆Entrega', '◆Mantenimiento'])
