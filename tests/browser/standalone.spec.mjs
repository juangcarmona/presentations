import { test, expect } from '@playwright/test'

test('catalogue opens one bilingual standalone keynote', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Enter talk' }).first().click()
  await expect(page).toHaveURL(/\/software-engineering-2_0\/$/)
  await expect(page.locator('.keynote')).toBeVisible()
  await expect(page.locator('.topbar, .footer, .site-shell, iframe')).toHaveCount(0)
  await expect(page.locator('.language-picker')).toBeVisible()
  const hud = await page.locator('.presentation-hud').boundingBox()
  expect(hud.x).toBeGreaterThan(800)
  expect(hud.y).toBeGreaterThan(600)
  await expect(page.locator('.presentation-hud > span').first()).toHaveText('0 min')
  await page.getByRole('button', { name: 'EN', exact: true }).click()
  await expect(page).toHaveURL(/\/software-engineering-2_0\/\?lang=en$/)
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.locator('#scene-title')).toHaveText('Software Engineering 2.0')
  await page.locator('#scene-title').focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('.language-picker')).toHaveCount(0)
  await expect(page.locator('.presentation-hud')).toContainText('2')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.keyboard.press('ArrowLeft')
  await page.getByRole('button', { name: 'ES', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'es')
  await expect(page).toHaveURL(/\/software-engineering-2_0\/#scene=cover$/)
})

test('diagram details stay near their node and phased slides advance locally', async ({ page }) => {
  await page.goto('/software-engineering-2_0/#scene=08-dimensiones')
  const what = page.getByRole('button', { name: /WHAT · Producto/ })
  await what.hover()
  const node = await what.boundingBox()
  const tip = await what.locator('.node-popover').boundingBox()
  expect(tip.x).toBeGreaterThan(node.x - 100)
  expect(tip.y - node.y).toBeLessThan(220)
  await page.goto('/software-engineering-2_0/#scene=20-piramide')
  await expect(page.locator('[data-scene="20-piramide"]')).toHaveAttribute('data-stage', '0')
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('[data-scene="20-piramide"]')).toHaveAttribute('data-stage', '1')
  await page.keyboard.press('ArrowRight')
  await expect(page).toHaveURL(/#scene=20b-power-bi-fabric$/)
})

test('original GIF is opt-in and can be stopped', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/software-engineering-2_0/#scene=13-productshape')
  await expect(page.locator('.demo-animation')).toHaveCount(0)
  await page.getByRole('button', { name: 'Reproducir demo animada' }).click()
  await expect(page.locator('.demo-animation')).toBeVisible()
  await page.getByRole('button', { name: 'Detener demo animada' }).click()
  await expect(page.locator('.demo-animation')).toHaveCount(0)
})
